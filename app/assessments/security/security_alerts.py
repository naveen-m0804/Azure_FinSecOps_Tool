import datetime
import time
from typing import List, Dict, Any
from app.assessments.base import BaseAssessment, AssessmentContext
from app.schemas.assessment import AssessmentResult, AssessmentStatus
from app.schemas.finding import FindingModel
from app.azure.defender import DefenderAdapter
from app.utils.resource_ids import parse_azure_resource_id

class HighSecurityAlertsAssessment(BaseAssessment):
    assessment_id = "security_alerts"
    code = "SEC-06"
    category = "security"
    name = "High Security Alerts"
    description = "Retrieve and report active High and Critical security alerts generated by Defender for Cloud."
    purpose = "Identify active threats, compromised entities, and suspicious behavior across subscriptions."
    required_permissions = ["Microsoft.Security/alerts/read", "Security Reader"]
    required_data_sources = ["Defender for Cloud Alerts API (2022-01-01)"]

    async def run(self, context: AssessmentContext) -> AssessmentResult:
        start_t = time.time()
        now_str = datetime.datetime.now(datetime.timezone.utc).isoformat()

        
        findings: List[FindingModel] = []
        errors: List[str] = []
        resources_evaluated = 0

        for sub in context.subscriptions:
            resp = await DefenderAdapter.get_security_alerts(context.client, sub.subscription_id)
            if not resp.get("success"):
                status_code = resp.get("status_code", 500)
                if status_code in (401, 403):
                    errors.append(f"Subscription '{sub.display_name}': Permission Missing (Microsoft.Security/alerts/read)")
                else:
                    errors.append(f"Subscription '{sub.display_name}': {resp.get('error', 'Error retrieving alerts')}")
                continue

            alerts = resp.get("value", [])
            for alert in alerts:
                resources_evaluated += 1
                props = alert.get("properties", {})
                severity = props.get("severity", "Medium")
                alert_status = props.get("status", "Active")

                # Only report active/investigating alerts with High or Medium severity
                if alert_status.lower() in ("active", "inprogress", "new") and severity.lower() in ("high", "critical", "medium"):
                    alert_name = props.get("alertDisplayName") or alert.get("name", "Security Alert")
                    compromised_entity = props.get("compromisedEntity") or ""
                    parsed = parse_azure_resource_id(compromised_entity) if compromised_entity else {}
                    rg_name = parsed.get("resource_group") or "Microsoft.Security"
                    res_name = parsed.get("resource_name") or compromised_entity or alert_name
                    res_type = parsed.get("resource_type") or "Microsoft.Security/alerts"
                    res_id = compromised_entity or alert.get("id", "")

                    start_time = props.get("startTimeUtc") or props.get("timeGeneratedUtc") or now_str
                    gen_time_str = start_time[:16].replace("T", " ") if start_time else now_str[:16].replace("T", " ")
                    description = props.get("description") or "Suspicious activity detected by Microsoft Defender for Cloud."
                    remediation = props.get("remediationSteps") or props.get("remediationDescription")
                    if isinstance(remediation, list):
                        remed_str = "\n".join(str(s) for s in remediation if s)
                    else:
                        remed_str = str(remediation).strip() if remediation else "--"
                    if not remed_str or remed_str == "--":
                        remed_str = f"Investigate and contain security alert '{alert_name}' on entity '{res_name}' in Defender for Cloud."
                    tactics = props.get("intent") or (", ".join(props.get("techniques", [])) if props.get("techniques") else "Execution / Persistence")

                    findings.append(
                        FindingModel(
                            finding_id=f"sec06-{sub.subscription_id[:8]}-{alert.get('name', '')[:10]}",
                            assessment_id=self.assessment_id,
                            category=self.category,
                            subscription_id=sub.subscription_id,
                            subscription_name=sub.display_name,
                            resource_group=rg_name,
                            resource_name=res_name,
                            resource_type=res_type,
                            resource_id=res_id,
                            region="global",
                            severity=severity.capitalize(),
                            status=alert_status.capitalize(),
                            current_configuration=description[:150],
                            measured_value=f"Active Alert: {alert_status.capitalize()}",
                            recommended_configuration=remed_str[:150] if remed_str != "--" else "Investigate and contain compromised identity or host",
                            recommendation=remed_str if remed_str != "--" else f"Investigate alert '{alert_name}' on entity '{res_name}'",
                            metric_period="Active alert state",
                            data_source="Defender for Cloud Alerts API (2022-01-01)",
                            evidence={
                                "alert_name": alert_name,
                                "severity": severity.capitalize(),
                                "status": alert_status.capitalize(),
                                "generated_time": gen_time_str,
                                "description": description,
                                "affected_entity": res_name,
                                "attack_tactics": tactics,
                            },
                            collected_at=now_str
                        )
                    )

        if errors and not findings:
            if any("Permission" in e for e in errors):
                status = AssessmentStatus.PERMISSION_MISSING
            else:
                status = AssessmentStatus.FAILED
        elif errors and findings:
            status = AssessmentStatus.COMPLETED_WITH_WARNINGS
        elif findings:
            status = AssessmentStatus.COMPLETED
        else:
            status = AssessmentStatus.NO_FINDINGS

        return AssessmentResult(
            assessment_id=self.assessment_id,
            category=self.category,
            name=self.name,
            status=status,
            resources_evaluated=max(resources_evaluated, len(context.subscriptions)),
            findings_count=len(findings),
            findings=findings,
            errors=errors,
            execution_time_seconds=round(time.time() - start_t, 2),
            last_run_time=now_str
        )
